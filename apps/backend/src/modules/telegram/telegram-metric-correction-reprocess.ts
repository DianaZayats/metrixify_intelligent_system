const REPROCESS_EXPLICIT =
  /(?:^|[\s,.:;!?—–-])(перечитай|перечитайте|перечитати|перевитяг|перевитягни|re-read|reprocess|re-extract|reextract|заново|знову)(?:$|[\s,.:;!?])|(?:перечит|reprocess|re-extract|re-read)/i;

const REPROCESS_INDIRECT = [
  /(?:метрик|метрики).{0,50}(?:не\s*те|неправильн|не\s*так|крив|чуж)/i,
  /(?:не\s*те|неправильн|не\s*так).{0,50}(?:метрик|метрики)/i,
  /(?:ещё|еще)\s*раз.{0,40}(?:посмотри|прочитай|разбери|витяг|извлек|анализ)/i,
  /(?:посмотри|прочитай|разбери|пересмотри).{0,40}(?:ещё|еще)\s*раз/i,
  /(?:заново|знову|с\s*начала).{0,35}(?:извлек|витяг|разбери|метрик|анализ)/i,
  /(?:извлек|витяг|разбери|анализ).{0,35}(?:заново|знову|с\s*начала)/i,
  /(?:пере|повторно).{0,25}(?:анализ|разбери|извлек|витяг)/i,
  /(?:два|2|двух)\s*дн.{0,35}(?:перечит|разбери|извлек|витяг|пересмотр|анализ)/i,
  /(?:пересмотри|переанализ).{0,35}(?:запис|entry|метрик|текст)/i,
  /(?:пропустил|упустил|не\s*вс[ёе]).{0,45}(?:перечит|заново|ещё\s*раз|извлек|витяг)/i,
  /(?:не\s*вс[ёе]|не\s*все).{0,45}(?:правильно|точно).{0,35}(?:извлек|витяг|понял|разобрал)/i,
  /(?:не\s*правильно|неправильно).{0,30}(?:понял|разобрал|извлек|витяг).{0,35}(?:запис|текст|entry)/i,
];

export function isReprocessCorrectionMessage(text: string): boolean {
  const normalized = text.trim();
  if (REPROCESS_EXPLICIT.test(normalized)) {
    return true;
  }
  return REPROCESS_INDIRECT.some((pattern) => pattern.test(normalized));
}
